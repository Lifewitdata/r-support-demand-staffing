# Run: Rscript scripts/run_pipeline.R (from the project root)
source('R/load.R')
for(path in c('data/raw','data/processed','outputs/figures')) dir.create(path,recursive=TRUE,showWarnings=FALSE)
validate_config(settings)
cat('Generating synthetic source data...\n')
inputs <- generate_inputs(settings)
quality <- validate_inputs(inputs$tickets,inputs$schedule,inputs$future,settings)
cat('Building hourly operations...\n')
hourly <- prepare_hourly(inputs$tickets,inputs$schedule,settings)
cat('Comparing models with chronological validation...\n')
bundle <- run_forecasts(hourly,settings)
plan <- staffing_plan(bundle$future_forecast,inputs$future,hourly,settings)
summary <- write_reports(hourly,bundle,plan,quality,settings)
saveRDS(list(hourly=hourly,forecast=bundle,future_schedule=inputs$future,quality=quality,settings=settings,
             built_at=format(Sys.time(),tz='UTC',usetz=TRUE)), 'data/processed/app_bundle.rds')
fwrite(data.table(package=c('R','data.table','ggplot2','shiny'),version=c(as.character(getRversion()),vapply(c('data.table','ggplot2','shiny'),function(x)as.character(packageVersion(x)),character(1)))),'outputs/package_versions.csv')
writeLines(capture.output(sessionInfo()),'outputs/session_info.txt')
cat(sprintf('Completed: %s tickets, %s queue-hours.\n',format(nrow(inputs$tickets),big.mark=','),format(nrow(hourly),big.mark=',')))
print(summary)
