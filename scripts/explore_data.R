# A readable EDA entrypoint for RStudio. Run the pipeline first.
source('R/load.R')
x <- readRDS('data/processed/hourly_operations.rds')
cat('1. Data grain and coverage\n')
print(x[,.(rows=.N,first=min(timestamp),last=max(timestamp),tickets=sum(arrivals)),by=queue])
cat('\n2. Weighted handling time and workload\n')
print(x[,.(aht=sum(workload_minutes)/sum(arrivals),workload_hours=sum(workload_minutes)/60,
           capacity_hours=sum(capacity_minutes)/60),by=queue])
cat('\n3. Weekly and daily demand patterns\n')
print(x[,.(mean_arrivals=mean(arrivals)),by=.(queue,dow)][order(queue,dow)])
print(x[,.(mean_arrivals=mean(arrivals)),by=.(queue,hour)][order(queue,-mean_arrivals)][,head(.SD,3),by=queue])
cat('\n4. Highest observed hourly volumes\n')
print(x[order(-arrivals)][1:10,.(timestamp,queue,arrivals,aht_minutes)])
cat('\n5. Latest workload change: volume versus handling time\n')
print(workload_decomposition(x))
cat('\n6. Validation, model comparison and later-week accuracy\n')
print(fread('outputs/selection_scores.csv'))
print(fread('outputs/holdout_scores.csv'))
print(fread('outputs/interval_coverage.csv'))
cat('\nInterpretation: arithmetic workload drivers are not causal process effects. See the weekly brief for actions and limitations.\n')
